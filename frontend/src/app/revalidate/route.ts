import { revalidateTag } from "next/cache";
import { NextRequest, NextResponse } from "next/server";
import { PUBLIC_CACHE_TAG } from "@/lib/api-server";

/**
 * Сброс кеша публичных страниц. Дёргается автоматически из lib/api.ts после
 * любой удачной изменяющей операции в админке -- см. clientFetch.
 *
 * Путь НЕ начинается с /api/ и не должен: за этим префиксом стоит nginx,
 * который целиком отдаёт /api/ бэкенду (см. nginx/nginx.conf). Пока роут
 * лежал в app/api/revalidate, в проде до него не доходил ни один запрос --
 * FastAPI отвечал 404, вызов молча проглатывался своим .catch(), и правка в
 * админке появлялась на сайте только через пять минут, когда кеш истекал
 * сам. Локально в dev-режиме, где nginx нет, всё при этом работало.
 *
 * Публичные страницы кешируют ответы бэкенда на пять минут (иначе каждый заход
 * любого посетителя означает полный SSR и поход в API). Без этого сброса
 * правка в админке не появлялась на сайте до истечения окна: админ
 * переименовывал турнир, в панели всё верно, а на публичной вкладке ещё
 * старое название.
 *
 * Гейт -- наличие сессионной куки, той же, что проверяет proxy.ts. Это не
 * авторизация (её делает бэкенд на самой мутации), а защита от того, чтобы
 * посторонний сбрасывал кеш в цикле: сама по себе операция безопасна, но
 * бесплатно ронять кеш чужого сайта не должно быть можно.
 */
// Второй способ позвать сброс -- из бэкенда. Правки мимо админки (кнопки в
// боте: подтверждение регистрации, применённая правка профиля, фото, отзыв
// согласия на публикацию) браузером не сопровождаются, и сбрасывать кеш было
// некому: сайт показывал прежнее до пяти минут. Для отзыва согласия это прямо
// противоречило обещанию на /privacy, что карточка исчезает сразу.
//
// Токен общий с бэкендом. Куку он не заменяет, а дополняет: браузерный путь
// остаётся как был.
const REVALIDATE_TOKEN = process.env.REVALIDATE_TOKEN;

function authorized(request: NextRequest): boolean {
  if (request.cookies.has("refresh_token")) return true;
  const token = request.headers.get("x-revalidate-token");
  // Пустой REVALIDATE_TOKEN не должен открывать ручку кому угодно: без
  // настроенного токена этот путь просто выключен.
  return Boolean(REVALIDATE_TOKEN) && token === REVALIDATE_TOKEN;
}

export async function POST(request: NextRequest) {
  if (!authorized(request)) {
    return NextResponse.json({ revalidated: false }, { status: 401 });
  }
  // Второй аргумент в Next 16 обязателен: профиль cacheLife или { expire }.
  // expire: 0 -- пометить помеченное тегом просроченным прямо сейчас, чтобы
  // следующий заход на публичную страницу сходил в API за свежими данными.
  revalidateTag(PUBLIC_CACHE_TAG, { expire: 0 });
  return NextResponse.json({ revalidated: true });
}
