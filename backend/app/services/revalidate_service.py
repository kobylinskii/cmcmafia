"""Сброс кеша публичных страниц сайта.

Фронтенд кеширует ответы API на пять минут (lib/api-server.ts, тег
"public-data") и сбрасывает кеш сам -- но только из браузера админки, после
удачной правки. Всё, что меняет публичные данные мимо админки, до этого
оставляло сайт несвежим: подтверждение регистрации из бота, применённая правка
профиля, загруженное фото и, что хуже всего, отзыв согласия на публикацию.

Последнее -- не косметика. На странице /privacy написано, что карточка
исчезает сразу; висящая ещё пять минут копия делает это обещание ложным.

Знает об изменениях бэкенд, поэтому и сбрасывает он.
"""

from __future__ import annotations

import logging

import httpx

from app.config import get_settings

logger = logging.getLogger(__name__)
settings = get_settings()


def revalidate_public_pages() -> None:
    """Попросить фронтенд забыть закешированные публичные страницы.

    Вызывается из BackgroundTasks, то есть уже после того, как ответ ушёл
    пользователю: сброс кеша не должен ни задерживать ответ, ни ронять
    удавшуюся операцию.

    Любая ошибка проглатывается намеренно и по той же причине, по какой это
    делает браузерная половина в lib/api.ts: данные уже записаны, и худшее,
    что случится при недоступном фронтенде, -- страница обновится сама через
    пять минут. Ронять из-за этого запись было бы хуже.
    """
    if not settings.revalidate_token:
        # Пустой токен -- осознанная конфигурация «сбрасывать некому»
        # (например, backend поднят без фронтенда). Молчим, а не шумим в логи
        # на каждую правку.
        return
    try:
        httpx.post(
            settings.frontend_revalidate_url,
            headers={"X-Revalidate-Token": settings.revalidate_token},
            timeout=3.0,
        )
    except Exception as exc:  # noqa: BLE001 -- см. docstring
        logger.warning("Не удалось сбросить кеш фронтенда: %s", exc)
