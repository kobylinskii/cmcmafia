"""Регистронезависимое сравнение текста в запросах.

Раньше и точное сравнение («ник уже занят», поиск игрока по @username), и
поиск подстроки шли через голый `.ilike(значение)`. Но ilike -- это LIKE, и
`%`/`_` из пользовательского ввода работали в нём как шаблон: ник состава
свободного (никаких ограничений, кроме длины), поэтому ник «%%» считался
занятым первым же существующим игроком, а @username «%» превращал точечный
поиск в шаблонный -- и `.one_or_none()` на двух совпадениях отдавал 500
вместо ответа.

Два разных случая и разводятся здесь на две функции: точное сравнение
шаблонов вообще не знает, а поиск экранирует их и ищет буквально.
"""

from __future__ import annotations

from sqlalchemy import ColumnElement, func

# Экранируем и сам escape-символ: иначе ник «100\» ломал бы уже сам шаблон.
_LIKE_SPECIALS = str.maketrans({"\\": r"\\", "%": r"\%", "_": r"\_"})


def ci_equals(column, value: str) -> ColumnElement[bool]:
    """Точное совпадение без учёта регистра -- для проверок «уже занято».

    Индекса по nickname/telegram_username нет и не было, так что lower()
    ничего не ломает по плану запроса.
    """
    return func.lower(column) == value.lower()


def ci_contains(column, value: str) -> ColumnElement[bool]:
    """Поиск подстроки: `%` и `_`, введённые человеком, ищутся буквально."""
    return column.ilike(f"%{value.translate(_LIKE_SPECIALS)}%", escape="\\")
